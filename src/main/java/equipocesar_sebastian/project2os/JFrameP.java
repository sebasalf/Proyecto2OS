    private void EliminarNodoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarNodoActionPerformed
        if(!rAdmin.isSelected()){
            JOptionPane.showMessageDialog(null, "Usted no es Administrador para Eliminar Archivos");
        }else if(jTree1.getSelectionPath() == null){
            JOptionPane.showMessageDialog(null, "Por favor seleccione en el Jtree su carpeta o archivo");
        }else{
            DefaultMutableTreeNode selectedNode = (DefaultMutableTreeNode) jTree1.getSelectionPath().getLastPathComponent();
            selectedNode.removeFromParent();
            DefaultTreeModel model = (DefaultTreeModel) jTree1.getModel();
            model.reload();
            
            block aux = blockList.getFirst();
            while(aux!=null){
                if(aux.getPertenencia().equals(selectedNode.getUserObject().toString())){
                    aux.setColor(Color.WHITE);
                    aux.setDisponible(true);
                    aux.setPertenencia("");
                }
                aux = aux.getpNext();
            }
            DefaultTableModel tbModel = (DefaultTableModel) FATable.getModel();
            for (int i = 0; i <= tbModel.getColumnCount(); i++) {
                String name = (String) tbModel.getValueAt(i, 0);
                if(name.equals(selectedNode.getUserObject().toString())){
                    tbModel.removeRow(i);
                    break;
                }
            } 
        }
    }//GEN-LAST:event_EliminarNodoActionPerformed

