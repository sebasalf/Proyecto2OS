    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(blockList.getSize() != 0){
            JFrame newframe = new JFrame();
            newframe.setSize(400,400);
            JPanel generalPanel = new JPanel();
            int blocks = blockList.getSize();
            int rows = (int) Math.sqrt(blocks);
            generalPanel.setLayout(new GridLayout(rows,0,3,3));

            JButton[] buttons = new JButton[blocks];
            for (int i = 0; i < blocks; i++) {
                buttons[i] = new JButton(String.valueOf(i));
                buttons[i].setBackground(blockList.getBlock(i).getColor());
                buttons[i].setOpaque(true);
                buttons[i].setBorderPainted(false);
                buttons[i].setFont(new Font("Italica", Font.BOLD, 12));
                generalPanel.add(buttons[i]);
            }
            newframe.add(generalPanel);
            newframe.setVisible(true);
        }else{
            JOptionPane.showMessageDialog(null, "Por favor ingrese el tamano de los bloques");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

