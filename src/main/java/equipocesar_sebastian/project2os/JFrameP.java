    private void AgregarArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AgregarArchivoActionPerformed

        if(Nombre.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Debe Ingresar un Nombre primero");
        }else if(blockList.getSize() == 0){
            JOptionPane.showMessageDialog(null, "Por favor Ingrese un numero de Bloques inicial");
        }else if(CantBloques.getText().equals("") || Integer.parseInt(CantBloques.getText()) <= 0 || Integer.parseInt(CantBloques.getText()) > blockList.getSize()){
            JOptionPane.showMessageDialog(null, "Por favor Ingrese un numero de Bloques de Archivo Valido (Menor a la cantidad Maxima y Mayor a 0,)");
        }else if(ColorDecidido.getSelectedIndex() == 0){
            JOptionPane.showMessageDialog(null, "Por favor seleccione un Color");
        }else if(jTree1.getSelectionPath() == null){
            JOptionPane.showMessageDialog(null, "Por favor seleccione en el Jtree su carpeta");
        }else{
            
            block aux = this.blockList.getFirst();
            try{
                while(aux != null){
                    if(aux.isDisponible()){
                        int contador = 0;
                        block aux2 = aux;
                        for (int i = 0; i < Integer.parseInt(CantBloques.getText()); i++) {
                            if(aux2.isDisponible()){
                                contador++;
                                aux2 = aux2.getpNext();
                                System.out.println(contador);
                            }
                        }
                        if (contador == Integer.parseInt(CantBloques.getText())){
                            String initial = String.valueOf(aux.getNumero());
                            for (int i = 0; i < contador; i++) {
                                aux.setDisponible(false);
                                aux.setColor(colours[ColorDecidido.getSelectedIndex()-1]);
                                aux.setPertenencia(Nombre.getText());
                                aux = aux.getpNext();
                                ;
                            }
                            DefaultMutableTreeNode selectedNode = (DefaultMutableTreeNode) jTree1.getSelectionPath().getLastPathComponent();
                            DefaultMutableTreeNode newNode = new DefaultMutableTreeNode(Nombre.getText(), false);     
                            selectedNode.add(newNode);
                            DefaultTreeModel model = (DefaultTreeModel) jTree1.getModel();
                            model.reload();
                            
                            String data[] = {Nombre.getText(), CantBloques.getText(), initial, String.valueOf(ColorDecidido.getSelectedItem())};
                            DefaultTableModel tblModel = (DefaultTableModel) FATable.getModel();
                            tblModel.addRow(data);
                            
                            return;
                        }else{
                            aux = aux2;
                        }
                    }
                    aux = aux.getpNext();
                }
            }catch(NullPointerException e){
                JOptionPane.showMessageDialog(null, "No hay suficiente espacio para el Archivo");
            }
        }
        
        
    }//GEN-LAST:event_AgregarArchivoActionPerformed

